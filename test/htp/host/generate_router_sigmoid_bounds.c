#include <fenv.h>
#include <inttypes.h>
#include <stdio.h>
#include <stdlib.h>

#include "m1_ops_det.h"

/* Enumerate every float bit pattern in 2^-24 <= |x| < 16. Tables outside
 * this range use the universal [0, 1] bound; tiny x uses the same universal
 * bound until an independent exactness argument is retained. */
#define FIRST_BITS 0x33800000u
#define LAST_BITS 0x41800000u
#define BUCKET_SHIFT 19u
#define BUCKETS ((LAST_BITS - FIRST_BITS) >> BUCKET_SHIFT)

int main(int argc, char **argv) {
  if (argc != 2 || fesetround(FE_TONEAREST))
    return 1;
  static uint32_t bounds[2][BUCKETS][2];
  uint64_t cases = 0;
#pragma omp parallel for schedule(static) reduction(+ : cases) num_threads(4)
  for (unsigned index = 0; index < 2u * BUCKETS; ++index) {
    const unsigned sign = index / BUCKETS, bucket = index % BUCKETS;
    uint32_t lo = 0x3f800000u, hi = 0;
    const uint32_t first = FIRST_BITS + (bucket << BUCKET_SHIFT);
    for (uint32_t bits = first; bits < first + (1u << BUCKET_SHIFT); ++bits) {
      const float logit = m1_det_float(bits | (sign << 31));
      const float ex =
        m1_expf_bionic_det(m1_det_float(m1_det_bits(logit) ^ 0x80000000u));
      const float denominator = m1_det_add(ex, 1.0f);
      volatile float sig = 1.0f / denominator;
      const uint32_t result = m1_det_bits(sig);
      if (result < lo)
        lo = result;
      if (result > hi)
        hi = result;
      ++cases;
    }
    bounds[sign][bucket][0] = lo;
    bounds[sign][bucket][1] = hi;
  }
  FILE *out = fopen(argv[1], "w");
  if (!out)
    return 1;
  fprintf(out,
          "// SPDX-License-Identifier: Apache-2.0\n"
          "/* Exact minima/maxima of the current Bionic sigmoid over "
          "all %" PRIu64 "\n"
          " * binary32 inputs with 2^-24 <= |logit| < 16. Generated by\n"
          " * generate_bounds.c; each bucket contains 2^19 inputs. */\n"
          "static const uint32_t router_sigmoid_bounds[2][%u][2] = {\n",
          cases, BUCKETS);
  for (unsigned sign = 0; sign < 2; ++sign) {
    fprintf(out, "  {\n");
    for (unsigned bucket = 0; bucket < BUCKETS; ++bucket)
      fprintf(out, "    {0x%08xu, 0x%08xu},\n", bounds[sign][bucket][0],
              bounds[sign][bucket][1]);
    fprintf(out, "  },\n");
  }
  fprintf(out, "};\n");
  if (fclose(out))
    return 1;
  printf("ROUTER_BOUND_ENUMERATION_PASSED cases=%" PRIu64
         " buckets=%u bytes=%zu\n",
         cases, 2u * BUCKETS, sizeof(bounds));
  return 0;
}
