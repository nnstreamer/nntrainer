/** Exhaustively complete the original table's finite binary32 domain. */
#include <fenv.h>
#include <inttypes.h>
#include <stdio.h>
#include <stdlib.h>

#include "router_bounds_reference.h"

int main(int argc, char **argv) {
  if (argc != 2 || fesetround(FE_TONEAREST))
    return 1;
  const uint32_t starts[2] = {0u, 0x41800000u};
  const uint32_t ends[2] = {0x33800000u, 0x7f800000u};
  uint32_t bounds[2][2][2] = {{{0x3f800000u, 0u}, {0x3f800000u, 0u}},
                              {{0x3f800000u, 0u}, {0x3f800000u, 0u}}};
  uint64_t counts[2][2] = {{0}};
  uint64_t cases = 0;
  unsigned invalid = 0;
  /* Split each of four ranges into chunks to balance ordinary/tail costs. */
#pragma omp parallel for schedule(dynamic, 1) reduction(+ : cases, invalid) num_threads(4)
  for (unsigned task = 0; task < 4u * 64u; ++task) {
    const unsigned sign = task / 128u;
    const unsigned region = (task / 64u) % 2u;
    const unsigned chunk = task % 64u;
    const uint32_t first = starts[region] + (chunk << 24);
    if (first >= ends[region])
      continue;
    const uint32_t last =
      first + (1u << 24) < ends[region] ? first + (1u << 24) : ends[region];
    uint32_t lo = 0x3f800000u, hi = 0;
    for (uint32_t bits = first; bits < last; ++bits) {
      float sig, score;
      prefill_router_sigmoid(m1_det_float(bits | (sign << 31)), 0.f, &sig,
                             &score);
      const uint32_t result = m1_det_bits(sig);
      invalid += result > 0x3f800000u;
      if (result < lo)
        lo = result;
      if (result > hi)
        hi = result;
      ++cases;
    }
#pragma omp critical
    {
      if (lo < bounds[sign][region][0])
        bounds[sign][region][0] = lo;
      if (hi > bounds[sign][region][1])
        bounds[sign][region][1] = hi;
      counts[sign][region] += last - first;
    }
  }
  if (invalid || cases != UINT64_C(3808428032)) {
    fprintf(stderr, "ENUMERATION_FAIL invalid=%u cases=%" PRIu64 "\n", invalid,
            cases);
    return 1;
  }
  FILE *out = fopen(argv[1], "w");
  if (!out)
    return 1;
  fprintf(out,
          "// SPDX-License-Identifier: Apache-2.0\n"
          "/* Exact minima/maxima over all %" PRIu64 " binary32 inputs\n"
          " * outside 2^-24 <= |logit| < 16. Index [sign][tiny/tail].\n"
          " * Generated by generate_outer_bounds.c. Nonfinite excluded. */\n"
          "static const uint32_t router_sigmoid_outer_bounds[2][2][2] = {\n",
          cases);
  for (unsigned sign = 0; sign < 2; ++sign) {
    fprintf(out, "  {\n");
    for (unsigned region = 0; region < 2; ++region) {
      fprintf(out, "    {0x%08xu, 0x%08xu},\n", bounds[sign][region][0],
              bounds[sign][region][1]);
      printf("OUTER_BOUND sign=%u region=%u cases=%" PRIu64
             " low=0x%08x high=0x%08x\n",
             sign, region, counts[sign][region], bounds[sign][region][0],
             bounds[sign][region][1]);
    }
    fprintf(out, "  },\n");
  }
  fprintf(out, "};\n");
  if (fclose(out))
    return 1;
  printf("ROUTER_OUTER_BOUND_ENUMERATION_PASSED cases=%" PRIu64 " bytes=%zu\n",
         cases, sizeof(bounds));
  return 0;
}
